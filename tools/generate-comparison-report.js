#!/usr/bin/env node
// generate-comparison-report.js
// Generate comprehensive comparison report

const fs = require('fs');
const path = require('path');
const { analyzeV7Rules, generateReport } = require('./v7-analysis');

function findLatestComparison() {
  const dir = 'ops/enhance/comparison';
  if (!fs.existsSync(dir)) return null;
  
  const files = fs.readdirSync(dir)
    .filter(f => f.startsWith('comparison-') && f.endsWith('.json'))
    .map(f => ({
      name: f,
      path: path.join(dir, f),
      mtime: fs.statSync(path.join(dir, f)).mtime
    }))
    .sort((a, b) => b.mtime - a.mtime);
  
  return files.length > 0 ? files[0].path : null;
}

function generateMarkdownReport() {
  const analysisReport = generateReport(analyzeV7Rules());
  const comparisonFile = findLatestComparison();
  
  let comparison = null;
  if (comparisonFile) {
    comparison = JSON.parse(fs.readFileSync(comparisonFile, 'utf8'));
  }
  
  const report = `# v7 Rules System: Comparison Report

Generated: ${new Date().toISOString()}

## Executive Summary

This report compares system behavior and efficiency **WITH** vs **WITHOUT** the v7.mdc rules system enabled.

## Key Findings

### Quantitative Analysis

#### Rules Overview
- **Total rules**: ${analysisReport.summary.totalRules}
- **Auto-run rules**: ${analysisReport.summary.autoRunRules}
- **Always-triggered rules**: ${analysisReport.summary.alwaysTriggeredRules}
- **Conditional rules**: ${analysisReport.summary.conditionalRules}
- **Process spawns per query**: ${analysisReport.summary.processSpawnsPerQuery}

#### Estimated Overhead
- **Per query**: ~${analysisReport.overhead.perQueryMs}ms
- **Per 100 queries**: ~${(analysisReport.overhead.perQueryMs * 100 / 1000).toFixed(2)}s
- **Estimated yearly overhead** (100 queries/day): ~${analysisReport.overhead.yearlyOverhead.toFixed(2)} minutes

${comparison && comparison.summary ? `
### Comparison Results

**WITHOUT v7 rules:**
- Average estimated overhead: ${comparison.summary.avgOverheadWithout ? comparison.summary.avgOverheadWithout.toFixed(2) : '0.00'}ms
- Process spawns: 0-1 (minimal)
- File I/O: Minimal

**WITH v7 rules:**
- Average estimated overhead: ${comparison.summary.avgOverheadWith ? comparison.summary.avgOverheadWith.toFixed(2) : '0.00'}ms
- Process spawns: ${analysisReport.summary.processSpawnsPerQuery}
- File I/O: Increased (proposals, tasks, telemetry)

**Overhead difference**: +${comparison.summary.overheadDifference ? comparison.summary.overheadDifference.toFixed(2) : '0.00'}ms per query${comparison.summary.avgOverheadWithout === 0 ? ' (N/A - going from 0ms)' : (comparison.summary.percentageIncrease ? (comparison.summary.percentageIncrease === Infinity || !isFinite(comparison.summary.percentageIncrease) ? ' (∞)' : ` (+${comparison.summary.percentageIncrease.toFixed(2)}%)`) : '')}
` : ''}

## Issues Identified

${analysisReport.issues.map((issue, i) => `
### ${i + 1}. [${issue.severity.toUpperCase()}] ${issue.rule}

**Issue**: ${issue.issue}

**Recommendation**: ${issue.recommendation}
`).join('')}

## Recommendations

${analysisReport.recommendations.map((rec, i) => `
### ${i + 1}. [${rec.priority.toUpperCase()}] ${rec.action}

**Impact**: ${rec.impact}

**Examples**:
${rec.examples.map(e => `- ${e}`).join('\n')}
`).join('')}

## Conclusion

${(() => {
  const overhead = analysisReport.overhead.perQueryMs;
  const hasIssues = analysisReport.issues.length > 0;
  
  if (overhead < 100 && !hasIssues) {
    return `**Recommendation: KEEP v7 rules enabled**

The overhead is minimal (<100ms per query) and the structured workflow provides value. Consider optimizing the identified issues to further improve efficiency.`;
  } else if (overhead < 500 && hasIssues) {
    return `**Recommendation: KEEP v7 rules enabled with OPTIMIZATIONS**

The overhead is moderate but manageable. However, the identified issues should be addressed:
- Replace \`.*\` patterns with specific regex
- Reduce process spawns where possible
- Add caching for file I/O operations`;
  } else {
    return `**Recommendation: CONSIDER DISABLING or SIGNIFICANTLY OPTIMIZING v7 rules**

The overhead is high (>500ms per query) and may not provide sufficient value. Options:
1. Disable rules and use tools manually when needed
2. Optimize high-impact issues first, then re-evaluate
3. Use selective enablement (disable low-value rules)`;
  }
})()}

## Next Steps

1. Review the identified issues and prioritize fixes
2. Implement recommended optimizations
3. Re-run comparison test after optimizations
4. Monitor actual usage patterns to validate estimates

---
*Report generated by v7-comparison-test tools*
`;

  const outputDir = 'ops/enhance/comparison';
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }
  
  const reportFile = path.join(outputDir, 'COMPARISON_REPORT.md');
  fs.writeFileSync(reportFile, report);
  
  console.log('=== Comparison Report Generated ===\n');
  console.log(report);
  console.log(`\n\nReport saved to: ${reportFile}`);
  
  return report;
}

if (require.main === module) {
  try {
    generateMarkdownReport();
  } catch (error) {
    console.error('[ERROR]', error);
    process.exit(1);
  }
}

module.exports = { generateMarkdownReport };

