#!/usr/bin/env node

/**
 * AI Governance Checker
 * Validates AI-generated code: AAIA documentation, hallucination prevention
 */

const fs = require('fs');
const path = require('path');

const AI_GOVERNANCE_RULES = {
    // Missing AAIA documentation
    missing_aaia: {
        check: (file, content) => {
            const hasAIComment = /@ai-generated|AI-generated|Generated by AI/i.test(content);
            const hasAAIA = /@aaia|AI-Assisted Implementation Artifact/i.test(content);
            return hasAIComment && !hasAAIA;
        },
        severity: 'HIGH',
        message: 'Missing AAIA documentation - AI-generated code must include @aaia block'
    },

    // Hallucinated APIs (common fake function names)
    hallucinated_api: {
        pattern: /(getUserData|fetchAllData|processData|handleRequest|doSomething|performAction)\(/g,
        severity: 'MEDIUM',
        message: 'Potential hallucinated API - generic function name (verify it exists in codebase)'
    },

    // Missing error handling in AI code
    missing_error_handling: {
        check: (file, content) => {
            const hasAIComment = /@ai-generated/i.test(content);
            const hasTryCatch = /try\s*{[\s\S]*catch/i.test(content);
            const hasErrorCheck = /if\s*\([^)]*error|throw new Error/i.test(content);
            return hasAIComment && !hasTryCatch && !hasErrorCheck && content.length > 200;
        },
        severity: 'HIGH',
        message: 'AI-generated code missing error handling - add try/catch or error checks'
    },

    // Deprecated patterns (AI using old syntax)
    deprecated_pattern: {
        pattern: /var\s+\w+\s*=|mysql_query|eval\(|document\.write/g,
        severity: 'HIGH',
        message: 'Deprecated pattern detected - AI may be using outdated syntax'
    },

    // Missing validation in AI code
    missing_validation: {
        check: (file, content) => {
            const hasAIComment = /@ai-generated/i.test(content);
            const hasUserInput = /\$_(GET|POST|REQUEST)|req\.(body|query|params)/i.test(content);
            const hasValidation = /validate|sanitize|filter_var|trim\(|strip_tags/i.test(content);
            return hasAIComment && hasUserInput && !hasValidation;
        },
        severity: 'CRITICAL',
        message: 'AI-generated code missing input validation - SECURITY RISK'
    },

    // AI temperature too high (creative code in critical areas)
    high_temperature_code: {
        check: (file, content) => {
            const isCritical = /auth|payment|security|admin/i.test(file);
            const hasCreativePatterns = /TODO|FIXME|experimental|workaround/i.test(content);
            return isCritical && hasCreativePatterns;
        },
        severity: 'HIGH',
        message: 'High-temperature AI code in critical area - review thoroughly'
    },

    // Missing human review flag
    missing_review_flag: {
        check: (file, content) => {
            const hasAIComment = /@ai-generated/i.test(content);
            const hasReviewFlag = /@reviewed-by|@human-verified/i.test(content);
            const isCritical = /auth|payment|security|database/i.test(file);
            return hasAIComment && isCritical && !hasReviewFlag;
        },
        severity: 'HIGH',
        message: 'AI-generated critical code missing human review flag - add @reviewed-by'
    },

    // Overly complex AI code (AI being too clever)
    overly_complex: {
        check: (file, content) => {
            const hasAIComment = /@ai-generated/i.test(content);
            const nestingLevel = (content.match(/\{/g) || []).length - (content.match(/\}/g) || []).length;
            const lineCount = content.split('\n').length;
            return hasAIComment && (nestingLevel > 5 || lineCount > 300);
        },
        severity: 'MEDIUM',
        message: 'Overly complex AI-generated code - simplify (KISS principle)'
    }
};

function checkFile(filePath) {
    const content = fs.readFileSync(filePath, 'utf8');
    const lines = content.split('\n');
    const issues = [];

    Object.entries(AI_GOVERNANCE_RULES).forEach(([name, config]) => {
        // Pattern-based checks
        if (config.pattern) {
            lines.forEach((line, index) => {
                if (config.pattern.test(line)) {
                    issues.push({
                        file: filePath,
                        line: index + 1,
                        severity: config.severity,
                        issue: name,
                        message: config.message,
                        code: line.trim()
                    });
                }
            });
        }

        // Custom check functions
        if (config.check && config.check(filePath, content)) {
            issues.push({
                file: filePath,
                line: 1,
                severity: config.severity,
                issue: name,
                message: config.message,
                code: '(See file)'
            });
        }
    });

    return issues;
}

function scanDirectory(dir, extensions = ['.php', '.js', '.ts', '.py', '.jsx', '.tsx']) {
    let allIssues = [];

    function scan(currentDir) {
        const entries = fs.readdirSync(currentDir, { withFileTypes: true });

        entries.forEach(entry => {
            const fullPath = path.join(currentDir, entry.name);

            if (entry.isDirectory() && !entry.name.startsWith('.') && entry.name !== 'node_modules') {
                scan(fullPath);
            } else if (entry.isFile() && extensions.some(ext => entry.name.endsWith(ext))) {
                const issues = checkFile(fullPath);
                allIssues = allIssues.concat(issues);
            }
        });
    }

    scan(dir);
    return allIssues;
}

function main() {
    const target = process.argv[2] || '.';
    console.log(`🤖 AI Governance Checker - Scanning: ${target}\n`);

    const stats = fs.statSync(target);
    const issues = stats.isDirectory() ? scanDirectory(target) : checkFile(target);

    if (issues.length === 0) {
        console.log('✅ No AI governance violations found\n');
        process.exit(0);
    }

    const critical = issues.filter(i => i.severity === 'CRITICAL');
    const high = issues.filter(i => i.severity === 'HIGH');
    const medium = issues.filter(i => i.severity === 'MEDIUM');

    console.log(`🚨 Found ${issues.length} AI governance issues:\n`);

    if (critical.length > 0) {
        console.log(`❌ CRITICAL (${critical.length}):`);
        critical.forEach(issue => {
            console.log(`   ${issue.file}:${issue.line}`);
            console.log(`   ${issue.message}`);
            console.log(`   ${issue.code}\n`);
        });
    }

    if (high.length > 0) {
        console.log(`⚠️  HIGH (${high.length}):`);
        high.slice(0, 10).forEach(issue => {
            console.log(`   ${issue.file}:${issue.line}`);
            console.log(`   ${issue.message}\n`);
        });
        if (high.length > 10) console.log(`   ... and ${high.length - 10} more\n`);
    }

    if (medium.length > 0) {
        console.log(`ℹ️  MEDIUM (${medium.length}) - Review recommended\n`);
    }

    process.exit(critical.length > 0 ? 1 : 2);
}

if (require.main === module) {
    main();
}

module.exports = { checkFile, scanDirectory };
